#!/usr/bin/env node
// Builds templates/<slug>/index.html for every entry in scripts/variants.mjs,
// plus the gallery at templates/index.html.
//
// Each variant reuses the <body> of the root index.html verbatim (so the copy
// can't drift) and swaps only the <head>: the live page's inline <style> is
// replaced by templates/_shared/base.css + templates/<slug>/style.css.
// Analytics and JSON-LD are dropped, and pages are marked noindex with the
// live page as canonical.
//
// Usage: node scripts/build-variants.mjs
// Copy edits belong in index.html; rerun this afterwards.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { variants } from './variants.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const templatesDir = join(root, 'templates');
const read = (p) => readFileSync(join(root, p), 'utf8');

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export function extractBody(html) {
  const m = html.match(/<body[^>]*>([\s\S]*)<\/body>/i);
  if (!m) throw new Error('index.html has no <body>');
  let body = m[1];
  // Drop the GA4 tag: its comment, the loader and the inline config script.
  body = body
    .replace(/[ \t]*<!--\s*Google tag[\s\S]*?-->\s*/i, '')
    .replace(/[ \t]*<script[^>]*googletagmanager\.com[^>]*><\/script>\s*/gi, '')
    .replace(/[ \t]*<script>(?:(?!<\/script>)[\s\S])*gtag\((?:(?!<\/script>)[\s\S])*<\/script>\s*/gi, '');
  if (/gtag|googletagmanager/i.test(body)) throw new Error('Failed to strip the GA4 tag from the body');
  // Variants live two levels down; assets stay shared in the root img/.
  body = body.replace(/(\s(?:src|href)=")(?:\/)?img\//g, '$1../../img/');
  if (/\s(?:src|href)="\/(?!\/)/.test(body)) throw new Error('Root-absolute path left in body; it would break on file://');
  return body;
}

function splitImports(css) {
  const links = [];
  const rest = css.replace(/^\s*@import\s+url\(\s*['"]?([^'")]+)['"]?\s*\)\s*;\s*$/gm, (_, url) => {
    links.push(url);
    return '';
  });
  return { links, css: rest.trim() };
}

function indent(text, pad) {
  return text.split('\n').map((l) => (l ? pad + l : l)).join('\n');
}

function variantPage(v, body, description) {
  const stylePath = join(templatesDir, v.slug, 'style.css');
  if (!existsSync(stylePath)) throw new Error(`Missing ${stylePath}`);
  const { links, css } = splitImports(readFileSync(stylePath, 'utf8'));
  const base = read('templates/_shared/base.css').trim();
  const fontLinks = links.length
    ? [
        '  <link rel="preconnect" href="https://fonts.googleapis.com" />',
        '  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />',
        ...links.map((u) => `  <link rel="stylesheet" href="${esc(u)}" />`),
      ].join('\n')
    : '';
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <!-- Generated by scripts/build-variants.mjs from index.html + templates/${v.slug}/style.css. Do not edit. -->
  <title>James Hawkins — ${esc(v.name)} variant</title>
  <meta name="description" content="${description}" />
  <meta name="robots" content="noindex, nofollow" />
  <link rel="canonical" href="https://jameshawkins.com/" />
  <link rel="icon" href="../../favicon.ico" sizes="32x32" />
  <link rel="apple-touch-icon" href="../../apple-touch-icon.png" />
  <meta name="theme-color" content="${esc(v.theme)}" />
${fontLinks}
  <style>
${indent(base, '    ')}

    /* ─── ${v.name} — after ${v.source} ─── */
${indent(css, '    ')}
  </style>
</head>
<body>${body}</body>
</html>
`;
}

function galleryPage() {
  const cards = variants
    .map(
      (v, i) => `    <li>
      <a class="card" href="${v.slug}/index.html">
        <span class="frame"><iframe src="${v.slug}/index.html" title="${esc(v.name)} preview" loading="lazy" tabindex="-1" aria-hidden="true"></iframe></span>
        <span class="label"><span class="num">${String(i + 1).padStart(2, '0')}</span> ${esc(v.name)}</span>
        <span class="meta">${esc(v.mode || '')}${v.blurb ? ' · ' + esc(v.blurb) : ''}</span>
      </a>
    </li>`,
    )
    .join('\n');
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <!-- Generated by scripts/build-variants.mjs. Do not edit. -->
  <title>Portfolio design variants</title>
  <meta name="robots" content="noindex, nofollow" />
  <link rel="icon" href="../favicon.ico" sizes="32x32" />
  <style>
    *, *::before, *::after { box-sizing: border-box; margin: 0; padding: 0; }
    body { font: 15px/1.5 -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; background: #f4f4f5; color: #18181b; padding: 3rem 2rem 4rem; }
    header { max-width: 1280px; margin: 0 auto 2rem; }
    h1 { font-size: 1.6rem; letter-spacing: -0.02em; }
    header p { color: #52525b; margin-top: 0.35rem; max-width: 70ch; }
    header a { color: inherit; }
    ul { list-style: none; display: grid; grid-template-columns: repeat(auto-fill, minmax(280px, 1fr)); gap: 1.5rem; max-width: 1280px; margin: 0 auto; }
    .card { display: block; text-decoration: none; color: inherit; background: #fff; border: 1px solid #e4e4e7; border-radius: 12px; overflow: hidden; transition: box-shadow 0.15s, transform 0.15s; }
    .card:hover, .card:focus-visible { box-shadow: 0 12px 32px rgba(0,0,0,0.1); transform: translateY(-2px); }
    .card:focus-visible { outline: 2px solid #2563eb; outline-offset: 2px; }
    .frame { display: block; position: relative; aspect-ratio: 16 / 11; overflow: hidden; border-bottom: 1px solid #e4e4e7; background: #fafafa; }
    .frame iframe { position: absolute; top: 0; left: 0; width: 1280px; height: 880px; border: 0; transform: scale(0.25); transform-origin: 0 0; pointer-events: none; }
    .label { display: block; padding: 0.85rem 1rem 0.1rem; font-weight: 600; }
    .num { color: #71717a; font-variant-numeric: tabular-nums; margin-right: 0.35rem; }
    .meta { display: block; padding: 0 1rem 0.9rem; font-size: 0.8rem; color: #52525b; }
    @media (prefers-reduced-motion: reduce) { .card { transition: none; } .card:hover { transform: none; } }
  </style>
</head>
<body>
  <header>
    <h1>Portfolio design variants</h1>
    <p>${variants.length} restyles of <a href="../index.html">index.html</a>, each after one design system from feimacode/open-design-agent-kit. Copy is identical in all of them; only layout and styling differ. Previews need an internet connection for web fonts.</p>
  </header>
  <ul>
${cards}
  </ul>
  <script>
    // Scale each 1280px-wide preview to fit its card.
    const fit = (f) => { f.querySelector('iframe').style.transform = 'scale(' + f.clientWidth / 1280 + ')'; };
    const ro = new ResizeObserver((es) => es.forEach((e) => fit(e.target)));
    document.querySelectorAll('.frame').forEach((f) => { fit(f); ro.observe(f); });
  </script>
</body>
</html>
`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const html = read('index.html');
  const body = extractBody(html);
  const description = (html.match(/<meta name="description" content="([^"]*)"/) || [])[1] || '';
  const only = process.argv.slice(2);
  for (const v of variants) {
    if (only.length && !only.includes(v.slug)) continue;
    writeFileSync(join(templatesDir, v.slug, 'index.html'), variantPage(v, body, description));
    console.log(`built templates/${v.slug}/index.html`);
  }
  writeFileSync(join(templatesDir, 'index.html'), galleryPage());
  console.log('built templates/index.html');
}
